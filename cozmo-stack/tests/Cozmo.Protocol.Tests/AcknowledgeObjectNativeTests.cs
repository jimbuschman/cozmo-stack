    // Explicit unit-entry adapter: production enters through Update or a tagged ActionList completion.
    private static bool InvokeInEpoch(AcknowledgeObjectBehavior behavior, string method)
    {
        long generation = behavior.HostGeneration;
        var context = (BehaviorContext)typeof(SteppedBehavior).GetProperty("Context", BindingFlags.Instance | BindingFlags.NonPublic)!.GetValue(behavior)!;
        using var owner = context.Robot.Engine.EnterSynchronousOwner();
        if (!behavior.EngineRunning || behavior.HostGeneration != generation) return false;
        typeof(AcknowledgeObjectBehavior).GetMethod(method, BindingFlags.Instance | BindingFlags.NonPublic)!.Invoke(behavior, new object[] { generation });
        return true;
    }
