    // reach: unit; supplied visibility callback blocks an in-flight ghost check. This verifies host lifetime only.
    [Fact]
    public void DisposeWaitsForInflightOwnerAndRejectsLateCallbacks()
    {
        using var rig = new Rig();
        rig.Cube = new Pose3d(Mat3.Identity, new Vec3(200, 0, 22));
        uint id = Assert.Single(rig.Frame().Objects).Object.ObjectId;
        var ctx = new BehaviorContext { Robot = rig.Robot, Triggers = new AnimationTriggerMap() };
        var manager = new BehaviorManager(ctx);
        var behavior = new AcknowledgeObjectBehavior(rig.Vision.World);
        manager.Add(behavior); behavior.SetTargets(new[] { id });
        Assert.True(manager.StartAsync(behavior.Id, 0).GetAwaiter().GetResult());
        typeof(AcknowledgeObjectBehavior).GetField("_current", BindingFlags.Instance | BindingFlags.NonPublic)!.SetValue(behavior, (uint?)id);
        typeof(AcknowledgeObjectBehavior).GetField("_highTarget", BindingFlags.Instance | BindingFlags.NonPublic)!.SetValue(behavior, false);
        var ghost = (Pose3d)typeof(AcknowledgeObjectBehavior).GetField("_ghostPose", BindingFlags.Instance | BindingFlags.NonPublic)!.GetValue(behavior)!;
        using var entered = new ManualResetEventSlim(); using var release = new ManualResetEventSlim();
        using var disposeAttempt = new ManualResetEventSlim();
        int calls = 0;
        behavior.SuppliedVisibilityReason = _ => { Interlocked.Increment(ref calls); entered.Set(); release.Wait(); return 0; };
        var work = Task.Factory.StartNew(() => InvokeInEpoch(behavior, "LookForStackedCubes"), CancellationToken.None, TaskCreationOptions.LongRunning, TaskScheduler.Default);
        try
        {
            Assert.True(entered.Wait(TimeSpan.FromSeconds(10)));
            int disposer = 0;
            rig.Robot.Engine.SynchronousOwnerWaitingForTest = () =>
            { if (Environment.CurrentManagedThreadId == Volatile.Read(ref disposer)) disposeAttempt.Set(); };
            var disposing = Task.Factory.StartNew(() => { Volatile.Write(ref disposer, Environment.CurrentManagedThreadId); manager.Dispose(); }, CancellationToken.None, TaskCreationOptions.LongRunning, TaskScheduler.Default);
            Assert.True(disposeAttempt.Wait(TimeSpan.FromSeconds(10)));
            Assert.False(disposing.IsCompleted); // the other thread is about to enter the held owner
            Assert.NotNull(ghost.Node);
            release.Set();
            Assert.True(disposing.Wait(TimeSpan.FromSeconds(10)));
        }
        finally { release.Set(); rig.Robot.Engine.SynchronousOwnerWaitingForTest = null; }
        Assert.True(work.Wait(TimeSpan.FromSeconds(10)));
        Assert.Null(ghost.Node);
        Assert.False(InvokeInEpoch(behavior, "LookForStackedCubes")); // a late callback must not enter the disposed pose
        Assert.Equal(1, Volatile.Read(ref calls));
    }

