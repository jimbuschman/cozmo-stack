    /// <summary>readData's check and call (0x15BA4..0x15BE8): all four of ac[0], ac[1], dc[0], dc[1] null.</summary>
    public void LoadDefaultTablesIfMissing()
    {
        if (_acHuffTblPtrs[0] != null || _acHuffTblPtrs[1] != null || _dcHuffTblPtrs[0] != null || _dcHuffTblPtrs[1] != null) return;
        _ = MyJpegLoadDht(DefaultDhtSegment, _acHuffTblPtrs, _dcHuffTblPtrs);
    }

    // my_jpeg_load_dht (0xE2B8): walks the segment; stops when 16 or fewer bytes remain; count > 256, count > remaining - 17 and a
    // selector above 3 return -1 (none of these can occur for the shipped static segment, whose lengths sum to exactly 416)
    private static int MyJpegLoadDht(byte[] data, JpegHuffTable?[] ac, JpegHuffTable?[] dc)
    {
        int length = ((data[2] << 8) + data[3]) - 2;
        int pos = 4;
        var bits = new byte[17];
        var huffval = new byte[256];     // the original copies 256 bytes from an uninitialised stack buffer; only `count` entries are ever read (U2)
        while (length > 16)
        {
            int tcTh = data[pos];
            bits[0] = 0;
            int count = 0;
            for (int i = 1; i <= 16; i++)
            {
                bits[i] = data[pos + i];
                count += bits[i];
            }
            if (count > 256) return -1;
            length -= 17;
            if (count > length) return -1;
            Array.Clear(huffval);
            for (int i = 0; i < count; i++) huffval[i] = data[pos + 17 + i];
            length -= count;
            pos += count + 17;
            JpegHuffTable?[] arr;
            int sel;
            if ((tcTh & 0x10) != 0)
            {
                sel = tcTh - 0x10;
                arr = ac;
            }
            else
            {
                sel = tcTh;
                arr = dc;
            }
            if ((uint)sel > 3) return -1;
            var t = arr[sel] ??= new JpegHuffTable();
            Array.Copy(bits, t.Bits, 17);
            Array.Copy(huffval, t.HuffVal, 256);
        }
        return length != 0 ? -1 : 0;
    }
