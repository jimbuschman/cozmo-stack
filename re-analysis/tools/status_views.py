"""Generate the mechanical status views from the manifest and the job status files.

Outputs (all generated; do not edit by hand):
  re-analysis/FIDELITY_PROGRESS.md   counts by status, subsystem, review state and verification
  re-analysis/jobs/STATUS.md         per builder job: queue note, status-file state, verification evidence files
  re-analysis/jobs/QUEUE.md          only the builder-lane rows whose note still begins "open" although
                                     status/<job>.md exists: that leading "open" clause is replaced by the
                                     status file's state. Every other note is left as the manager wrote it.

The views keep three things apart and never infer one from another:
  implemented  - a builder status file says DONE (rows built; MISSINGs may remain)
  verified     - a check/verify file under re-analysis/research names the job (evidence exists; read it for the verdict)
  accepted     - the subsystem's review state in the manifest is ACCEPTED

Usage: python -I re-analysis/tools/status_views.py [--check]
  --check  exit 1 if any generated file is out of date (writes nothing)
"""
import collections
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
RA = os.path.join(ROOT, 're-analysis')
MANIFEST = os.path.join(RA, 'fidelity_manifest.json')
JOBS = os.path.join(RA, 'jobs')
STATUS_DIR = os.path.join(JOBS, 'status')
QUEUE = os.path.join(JOBS, 'QUEUE.md')
RESEARCH = os.path.join(RA, 'research')
ORDER = ['EXACT_SOURCE', 'EQUIVALENT_IMPLEMENTATION', 'COMPATIBILITY_POLICY', 'HARDWARE_ONLY', 'BLOCKED_EXTERNAL',
         'IMPLEMENTATION_GAP', 'RECOVERABLE_GAP']
HEADER = '<!-- Generated by re-analysis/tools/status_views.py from {src}. Do not edit by hand; rerun the tool. -->\n\n'
ROW = re.compile(r'^\| *([^|]+?) *\| *\[([A-Za-z0-9-]+)\]\(([^)]+)\) *\| *(.*?) *\|\s*$')


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def status_state(job):
    path = os.path.join(STATUS_DIR, job + '.md')
    if not os.path.exists(path):
        return None, None
    for line in read(path).splitlines():
        line = line.strip()
        if line:
            word = re.match(r'[A-Z]+', line)
            return (word.group(0) if word else line.split()[0]), line
    return 'EMPTY', ''


def research_files():
    out = []
    for d, _, fs in os.walk(RESEARCH):
        for f in fs:
            if f.endswith('.md'):
                out.append(os.path.relpath(os.path.join(d, f), RA).replace(os.sep, '/'))
    return sorted(out)


def evidence_for(job, files):
    key = job.lower()
    pat = re.compile(r'(^|[^a-z0-9])' + re.escape(key) + r'([^a-z0-9]|$)')
    return [f for f in files if pat.search(os.path.basename(f).lower()) and ('check' in f or 'verif' in f or 'pass' in f)]


def progress(m):
    recs = m['records']
    subs = m['subsystems']
    total = collections.Counter(r['status'] for r in recs)
    by = collections.defaultdict(collections.Counter)
    live_open = collections.Counter()
    ver = collections.Counter()
    for r in recs:
        by[r['subsystem']][r['status']] += 1
        if r.get('live_path') and r['status'] in ('IMPLEMENTATION_GAP', 'RECOVERABLE_GAP'):
            live_open[r['subsystem']] += 1
        v = r.get('verification')
        ver[(v or {}).get('level', 'NONE') if isinstance(v, dict) else (v or 'NONE')] += 1
    o = [HEADER.format(src='re-analysis/fidelity_manifest.json'), '# Fidelity progress\n\n',
         'Counts are read from the manifest. A status says what the evidence supports; it is not a claim that the stack ',
         'is built or tested. Verification (capture or hardware) is counted separately and never raises a status. ',
         'A subsystem is finished only when its review state is ACCEPTED.\n\n',
         '## Records by status\n\n| status | records |\n| --- | ---: |\n']
    for s in ORDER + sorted(set(total) - set(ORDER)):
        if total.get(s):
            o.append(f'| {s} | {total[s]} |\n')
    o.append(f'| **total** | **{len(recs)}** |\n\n')
    o.append('## Subsystems\n\n| subsystem | review | approved | records | EXACT | policy/equiv | HW_ONLY/BLOCKED | IMPL_GAP | RECOVERABLE | live-path open |\n')
    o.append('| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n')
    for s in subs:
        c = by.get(s['id'], collections.Counter())
        rv = s.get('review', {})
        o.append(f"| {s['id']} | {rv.get('state', '')} | {rv.get('approved') or rv.get('accepted') or ''} | {sum(c.values())} | "
                 f"{c['EXACT_SOURCE']} | {c['COMPATIBILITY_POLICY'] + c['EQUIVALENT_IMPLEMENTATION']} | "
                 f"{c['HARDWARE_ONLY'] + c['BLOCKED_EXTERNAL']} | {c['IMPLEMENTATION_GAP']} | {c['RECOVERABLE_GAP']} | {live_open[s['id']]} |\n")
    acc = [s['id'] for s in subs if s.get('review', {}).get('state') == 'ACCEPTED']
    o.append(f"\nACCEPTED subsystems: {', '.join(acc) if acc else 'none'}.\n\n")
    o.append('## Verification (independent of status)\n\n| level | records |\n| --- | ---: |\n')
    for k in sorted(ver):
        o.append(f'| {k} | {ver[k]} |\n')
    return ''.join(o)


def queue_rows(text):
    rows = []
    lane = None
    for i, line in enumerate(text.splitlines()):
        if line.startswith('## '):
            lane = 'builder' if line.startswith('## Builder lane') else ('research' if line.startswith('## Research lane') else None)
            continue
        mm = ROW.match(line)
        if mm and lane:
            rows.append((i, lane, mm.group(1), mm.group(2), mm.group(3), mm.group(4)))
    return rows


def fix_queue(text):
    lines = text.splitlines(keepends=True)
    changed = []
    for i, lane, pos, job, link, note in queue_rows(text):
        if lane != 'builder' or not re.match(r'open\b', note):
            continue
        state, _ = status_state(job)
        if not state:
            continue
        rest = re.sub(r'^open\b,?\s*(NEXT\b,?\s*)?(after [A-Za-z0-9-]+\b,?\s*)?', '', note).strip()
        new = f'{state} per status/{job}.md' + (f' {rest}' if rest.startswith('(') else (f'; {rest}' if rest else ''))
        eol = '\n' if lines[i].endswith('\n') else ''
        lines[i] = f'| {pos} | [{job}]({link}) | {new} |{eol}'
        changed.append(job)
    return ''.join(lines), changed


def status_md(text):
    files = research_files()
    o = [HEADER.format(src='jobs/QUEUE.md, jobs/status/*.md and research/ file names'), '# Builder job status\n\n',
         '- **Implemented** is the first line of `status/<job>.md` (DONE means the checked rows are built; MISSINGs may remain).\n',
         '- **Verification evidence** lists check/verify files under `re-analysis/research/` whose name contains the job id. ',
         'Their presence is not a verdict: open the file. Verdicts recorded only in `PROJECT_STATE.md` are not detected.\n',
         '- **Accepted** is per subsystem: see `FIDELITY_PROGRESS.md`.\n\n',
         '| # | job | queue note | status file | verification evidence |\n| --- | --- | --- | --- | --- |\n']
    for _, lane, pos, job, link, note in queue_rows(text):
        if lane != 'builder':
            continue
        _, first = status_state(job)
        ev = evidence_for(job, files)
        cell = (first or 'no status file').replace('|', '/')
        if len(cell) > 140:
            cell = cell[:137] + '...'
        qn = note.replace('|', '/')
        if len(qn) > 90:
            qn = qn[:87] + '...'
        o.append(f"| {pos} | {job} | {qn} | {cell} | {', '.join('`' + e + '`' for e in ev) or 'none found'} |\n")
    return ''.join(o)


def main():
    check = '--check' in sys.argv
    m = json.loads(read(MANIFEST))
    q = read(QUEUE)
    q2, changed = fix_queue(q)
    outs = {os.path.join(RA, 'FIDELITY_PROGRESS.md'): progress(m),
            os.path.join(JOBS, 'STATUS.md'): status_md(q2),
            QUEUE: q2}
    stale = [p for p, t in outs.items() if not os.path.exists(p) or read(p) != t]
    if check:
        for p in stale:
            print('out of date:', os.path.relpath(p, ROOT))
        return 1 if stale else 0
    for p in stale:
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write(outs[p])
        print('wrote', os.path.relpath(p, ROOT))
    if changed:
        print('queue rows updated from status files:', ', '.join(changed))
    return 0


if __name__ == '__main__':
    sys.exit(main())
