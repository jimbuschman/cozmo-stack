"""Generate the AnimationTrigger enum from the decompiled Unity authority.

The enum is Anki's, not ours: the names and their order come from
unity/scripts/csharp/Anki.Cozmo/AnimationTrigger.cs in the official 3.4.0 APK. Declaration order is the
ordinal, because the decompiled enum assigns no explicit values.

    python re-analysis/tools/generate_animation_triggers.py           # write
    python re-analysis/tools/generate_animation_triggers.py --check   # verify, for CI

Cross-check performed on every run: every CladEvent in the OBB's AnimationTriggerMap.json must name a
trigger this enum defines. A mismatch means one of the two inputs is from a different build.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CSHARP = ROOT / "unity" / "scripts" / "csharp" / "Anki.Cozmo" / "AnimationTrigger.cs"
TRIGGER_MAP = (ROOT / "re-analysis" / "obb" / "assets" / "cozmo_resources" / "assets"
               / "animationGroupMaps" / "AnimationTriggerMap.json")
OUT = ROOT / "cozmo-stack" / "src" / "Cozmo.Robot" / "Behavior" / "AnimationTrigger.g.cs"
REACTION_CSHARP = ROOT / "unity" / "scripts" / "csharp" / "Anki.Cozmo" / "ReactionTrigger.cs"
REACTION_OUT = ROOT / "cozmo-stack" / "src" / "Cozmo.Robot" / "Behavior" / "ReactionTrigger.g.cs"


def read_reactions():
    """ReactionTrigger: the engine's own set of things worth reacting to. Ends with Count, NoneTrigger."""
    src = REACTION_CSHARP.read_text(encoding="utf-8")
    body = src.split("{", 1)[1].rsplit("}", 1)[0]
    names = []
    for line in body.splitlines():
        line = line.strip().rstrip(",").strip()
        if not line or line.startswith("//"):
            continue
        names.append(line)
    if "Count" not in names:
        raise SystemExit("expected ReactionTrigger to contain Count")
    return [n for n in names if n not in ("Count", "NoneTrigger")]


def render_reactions(names):
    lines = [
        "// <auto-generated>",
        "//     Generated by re-analysis/tools/generate_animation_triggers.py. Do not edit by hand.",
        "//",
        "//     Source: unity/scripts/csharp/Anki.Cozmo/ReactionTrigger.cs, decompiled from the official",
        "//     3.4.0-1204 APK. Declared `: byte`, so these ordinals go on the wire as written.",
        "//     Count and NoneTrigger are sentinels and are left out.",
        "// </auto-generated>",
        "",
        "namespace Cozmo.Robot.Behavior;",
        "",
        "/// <summary>",
        "/// The things the shipped engine treats as worth reacting to. Anki's own set, not ours:",
        f"/// {len(names)} of them. What a reaction then plays is decided by "
        "<see cref=\"ReactionTable\"/>.",
        "/// </summary>",
        "public enum ReactionTrigger : byte",
        "{",
    ]
    lines += [f"    {n}," for n in names]
    lines += ["}", ""]
    return "\n".join(lines)


def read_triggers():
    src = CSHARP.read_text(encoding="utf-8")
    body = src.split("{", 1)[1].rsplit("}", 1)[0]
    names = []
    for line in body.splitlines():
        line = line.strip().rstrip(",").strip()
        if not line or line.startswith("//"):
            continue
        if "=" in line:
            raise SystemExit(f"unexpected explicit value in the enum: {line!r}")
        names.append(line)
    if not names or names[-1] != "Count":
        raise SystemExit("expected the enum to end with Count")
    return names[:-1]


def cross_check(names):
    if not TRIGGER_MAP.exists():
        return "AnimationTriggerMap.json not present; skipped the cross-check"
    pairs = json.loads(TRIGGER_MAP.read_text(encoding="utf-8"))["Pairs"]
    mapped = {p["CladEvent"] for p in pairs}
    missing = sorted(mapped - set(names))
    if missing:
        raise SystemExit(f"{len(missing)} mapped triggers are not in the enum, e.g. {missing[:5]}")
    return f"all {len(mapped)} mapped triggers exist in the enum; {len(names) - len(mapped)} triggers have no group"


def render(names, note):
    lines = [
        "// <auto-generated>",
        "//     Generated by re-analysis/tools/generate_animation_triggers.py. Do not edit by hand.",
        "//",
        "//     Source: unity/scripts/csharp/Anki.Cozmo/AnimationTrigger.cs, decompiled from the official",
        "//     3.4.0-1204 APK. The names and their order are Anki's; declaration order is the ordinal,",
        "//     because the decompiled enum assigns no explicit values.",
        f"//     Cross-check: {note}",
        "// </auto-generated>",
        "",
        "namespace Cozmo.Robot.Behavior;",
        "",
        "/// <summary>",
        "/// Every animation trigger the shipped engine defines: the names it uses to ask for an animation",
        f"/// without naming a clip. {len(names)} of them, mapped to animation groups by AnimationTriggerMap.json.",
        "/// </summary>",
        "public enum AnimationTrigger",
        "{",
    ]
    lines += [f"    {n}," for n in names]
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    names = read_triggers()
    note = cross_check(names)
    text = render(names, note)
    reactions = read_reactions()
    reaction_text = render_reactions(reactions)

    if "--check" in sys.argv:
        bad = 0
        for path, want in ((OUT, text), (REACTION_OUT, reaction_text)):
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current.replace("\r\n", "\n") != want:
                print(f"OUT OF DATE: {path}")
                bad = 1
        if not bad:
            print(f"up to date: {len(names)} animation triggers, "
                  f"{len(reactions)} reaction triggers; {note}")
        return bad

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    REACTION_OUT.write_text(reaction_text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} with {len(names)} triggers; {note}")
    print(f"wrote {REACTION_OUT} with {len(reactions)} reaction triggers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
